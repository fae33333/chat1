// yt-cookies.js — إدارة كوكيز يوتيوب المستخدمة مع yt-dlp (صيغة Netscape) بدون إعادة تشغيل الخادم.
// لا تُخزَّن الكوكيز في المستودع: تُكتب في مجلد data/ (مستثنى من git) بصلاحيات 600.
'use strict';

const fs = require('fs');
const path = require('path');

const COOKIE_FILE_RE = /^yt-cookies(?:-[a-z0-9_-]{1,24})?\.txt$/i;
const LOGIN_COOKIE_NAMES = ['SID', '__Secure-1PSID', '__Secure-3PSID', 'SAPISID', '__Secure-1PAPISID', '__Secure-3PAPISID', 'LOGIN_INFO'];
const CRITICAL_COOKIE_NAMES = ['SID', '__Secure-1PSID', '__Secure-3PSID', 'HSID', 'SSID', 'APISID', 'SAPISID', 'LOGIN_INFO'];

function cookieDir(root) {
  return path.join(root, 'data');
}

function isYoutubeDomain(domain) {
  return /(^|\.)youtube\.com$/i.test(String(domain || '').trim()) || /(^|\.)youtube-nocookie\.com$/i.test(String(domain || '').trim());
}

/** يحلل نص Netscape ويعيد ملخصاً صالحاً للتحقق من الحالة. */
function parseNetscape(text) {
  const info = { youtube: 0, login: false, expired: false, expiresAt: 0, bad: 0, names: [] };
  const names = new Set();
  let criticalExpiry = 0;
  for (const raw of String(text || '').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    // سطور HttpOnly تبدأ بعلامة # لكنها كوكيز حقيقية (HSID/SSID...) — لا نتجاهلها
    if (line.startsWith('#') && !/^#HttpOnly_/i.test(line)) continue;
    const parts = line.replace(/^#HttpOnly_/i, '').split('\t');
    if (parts.length < 7) { info.bad++; continue; }
    if (!isYoutubeDomain(parts[0])) continue;
    info.youtube++;
    const name = parts[5];
    names.add(name);
    const exp = Number(parts[4] || 0);
    if (exp > 0 && CRITICAL_COOKIE_NAMES.includes(name)) {
      criticalExpiry = criticalExpiry ? Math.min(criticalExpiry, exp) : exp;
    }
    if (LOGIN_COOKIE_NAMES.includes(name)) info.login = true;
  }
  info.names = [...names];
  if (criticalExpiry) {
    info.expiresAt = criticalExpiry;
    info.expired = criticalExpiry * 1000 <= Date.now();
  }
  return info;
}

/** JSON (EditThisCookie / Cookie-Editor) إلى Netscape. */
function jsonToNetscape(input) {
  let arr;
  try { arr = JSON.parse(input); } catch (e) { throw new Error('صيغة JSON غير صحيحة — تأكد أنك نسخت الملف كاملاً'); }
  if (!Array.isArray(arr)) arr = Array.isArray(arr && arr.cookies) ? arr.cookies : [];
  if (!arr.length) throw new Error('لم نجد أي كوكيز داخل الملف');
  const lines = ['# Netscape HTTP Cookie File', '# Generated by SoulChill admin panel', ''];
  let added = 0;
  for (const c of arr) {
    if (!c || typeof c !== 'object') continue;
    const name = String(c.name || '');
    if (!name) continue;
    let domain = String(c.domain || '');
    if (!domain && c.url) { try { domain = new URL(c.url).hostname; } catch (e) { domain = ''; } }
    if (!domain) domain = 'youtube.com';
    domain = domain.trim();
    if (!domain.startsWith('.')) domain = '.' + domain.replace(/^www\./i, '');
    const value = String(c.value == null ? '' : c.value);
    const p = String(c.path || '/');
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const exp = Math.floor(Number(c.expirationDate || c.expires || 0) || (Date.now() / 1000 + 180 * 86400));
    lines.push([domain, 'TRUE', p, secure, exp, name, value].join('\t'));
    added++;
  }
  if (!added) throw new Error('لم نجد أي كوكيز صالحة داخل الملف');
  return lines.join('\n');
}

/**
 * يقبل نصاً ملصوقاً بصيغ مختلفة (Netscape، JSON، نص مُهرَّب من HTML) ويعيد ملف Netscape نظيفاً.
 * يرمي خطأً عربياً واضحاً إذا لم يوجد أي كوكي يوتيوب.
 */
function normalizeCookieText(input) {
  let text = String(input == null ? '' : input).replace(/^\uFEFF/, '').trim();
  if (!text) throw new Error('الصق محتوى ملف الكوكيز أولاً');
  // نص ملصوق من صفحة HTML أو من محادثة: يفك ترميز الجداول والأمبيرساند
  if (/&#9;|&#x9;|&amp;/.test(text)) {
    text = text.replace(/&#9;/g, '\t').replace(/&#x9;/gi, '\t').replace(/&amp;/g, '&');
  }
  // بعض تطبيقات المحادثة تحوّل youtube.com إلى رابط Markdown: .[youtube.com](http://youtube.com)
  text = text.replace(/\[([^\]]+)\]\((?:https?:\/\/[^)]+)\)/g, '$1');
  if (/^[\[{]/.test(text)) text = jsonToNetscape(text);

  const out = ['# Netscape HTTP Cookie File', '# Generated by SoulChill admin panel', ''];
  let converted = 0;
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.replace(/\s+$/, '');
    if (!line.trim()) continue;
    const httpOnly = /^#HttpOnly_/i.test(line);
    if (line.startsWith('#') && !httpOnly) continue;
    let body = line.replace(/^#HttpOnly_/i, '');
    let parts = body.split('\t');
    if (parts.length < 7) {
      // بعض الملفات تُلصق بمسافات بدل التبويبات
      const spaced = body.split(/\s+/);
      if (spaced.length === 7) { parts = spaced; converted++; }
      else { continue; }
    }
    if (parts.length < 7) continue;
    const domain = parts[0].trim();
    if (!isYoutubeDomain(domain)) continue; // نتجاهل نطاقات أخرى مثل google.com لتقليل الحجم
    const secure = /^(true|false)$/i.test(parts[3]) ? parts[3].toUpperCase() : 'TRUE';
    const exp = Number(parts[4]) > 0 ? Math.floor(Number(parts[4])) : (Date.now() / 1000 + 180 * 86400) | 0;
    out.push((httpOnly ? '#HttpOnly_' : '') + [domain, 'TRUE', parts[2] || '/', secure, exp, parts[5], parts[6] || ''].join('\t'));
  }
  const info = parseNetscape(out.join('\n'));
  if (!info.youtube) throw new Error('الملف لا يحتوي كوكيز youtube.com — سجّل الدخول إلى يوتيوب ثم صدّر الكوكيز من جديد');
  if (info.expired) throw new Error('هذه الكوكيز منتهية الصلاحية — سجّل الدخول من جديد ثم صدّرها');
  return { text: out.join('\n') + '\n', info, converted };
}

/** كل ملفات الكوكيز المتاحة (المتغير البيئي + جذر المشروع + مجلد data) — الأحدث أولاً. */
function listCookieFiles(root) {
  const out = [];
  const seen = new Set();
  const add = (p) => {
    if (!p) return;
    const full = path.isAbsolute(p) ? p : path.join(root, p);
    if (seen.has(full)) return;
    try {
      const st = fs.statSync(full);
      if (!st.isFile() || st.size < 20) return;
      seen.add(full);
      out.push({ file: full, mtime: st.mtimeMs });
    } catch (e) { /* غير موجود */ }
  };
  for (const raw of String(process.env.YTDLP_COOKIES || '').split(/[;,]/)) add(raw.trim());
  add('cookies.txt');
  add(path.join('bin', 'cookies.txt'));
  const dir = cookieDir(root);
  try {
    for (const name of fs.readdirSync(dir)) {
      if (COOKIE_FILE_RE.test(name)) add(path.join(dir, name));
    }
  } catch (e) { /* لا يوجد مجلد data بعد */ }
  return out.sort((a, b) => b.mtime - a.mtime).map(x => x.file);
}

function describeCookieFile(file) {
  const st = fs.statSync(file);
  let text = '';
  try { text = fs.readFileSync(file, 'utf8'); } catch (e) { /* ملف غير قابل للقراءة */ }
  const info = parseNetscape(text);
  return {
    name: path.basename(file),
    size: st.size,
    modified: new Date(st.mtimeMs).toISOString(),
    youtubeCookies: info.youtube,
    loggedIn: info.login,
    expired: info.expired,
    expiresAt: info.expiresAt ? new Date(info.expiresAt * 1000).toISOString() : '',
    accounts: info.names.filter(n => LOGIN_COOKIE_NAMES.includes(n)).length
  };
}

function describeAll(root) {
  return listCookieFiles(root).map(file => {
    try { return describeCookieFile(file); } catch (e) { return null; }
  }).filter(Boolean);
}

function safeName(name) {
  const n = String(name || '').trim().toLowerCase();
  return /^[a-z0-9_-]{1,24}$/.test(n) ? n : '';
}

/** يحفظ نص الكوكيز في data/yt-cookies[-name].txt ويعيد وصفه. */
function saveCookieFile(root, input, name) {
  const { text, info } = normalizeCookieText(input);
  const dir = cookieDir(root);
  fs.mkdirSync(dir, { recursive: true });
  let base = safeName(name);
  if (!base) {
    base = 'yt-cookies';
    let i = 2;
    while (fs.existsSync(path.join(dir, base + '.txt')) && i < 50) { base = 'yt-cookies-' + i; i++; }
    if (base === 'yt-cookies' && fs.existsSync(path.join(dir, base + '.txt'))) base = 'yt-cookies-' + Date.now();
  } else {
    base = 'yt-cookies-' + base;
  }
  const file = path.join(dir, base + '.txt');
  fs.writeFileSync(file, text, { mode: 0o600 });
  try { fs.chmodSync(file, 0o600); } catch (e) { /* Windows */ }
  return { file, name: path.basename(file), info, description: describeCookieFile(file) };
}

/** يحذف ملف كوكيز رُفع من اللوحة فقط (وليس cookies.txt اليدوي). */
function deleteCookieFile(root, name) {
  const base = String(name || '').trim();
  if (!COOKIE_FILE_RE.test(base)) throw new Error('اسم ملف غير صالح');
  const file = path.join(cookieDir(root), base);
  if (path.dirname(file) !== cookieDir(root)) throw new Error('مسار غير صالح');
  if (!fs.existsSync(file)) throw new Error('الملف غير موجود');
  fs.unlinkSync(file);
  return true;
}

module.exports = {
  cookieDir,
  parseNetscape,
  normalizeCookieText,
  listCookieFiles,
  describeCookieFile,
  describeAll,
  saveCookieFile,
  deleteCookieFile,
  COOKIE_FILE_RE,
  LOGIN_COOKIE_NAMES
};
